#!/usr/bin/env bash
# verify_doc_prose.py over fixture repos, and its run-lint-gates.sh half; -k <section> picks cases. See docs/code-quality-tooling.md#doc-prose-doc-prose
set -u
TESTS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${TESTS_DIR}/test-harness.sh"
PY="${PREFLIGHT_PYTHON:-python3}"
SCRIPTS="${TESTS_DIR%/tests}"
GATE="${SCRIPTS}/verify_doc_prose.py"
_work="$(t_mktemp -d)"

# _sentences <count> <words> [word]: that many sentences of exactly that many words, one per line.
_sentences() {
  local i j
  for ((i = 0; i < $1; i++)); do
    printf 'Alpha'
    for ((j = 1; j < $2; j++)); do printf ' %s' "${3:-word}"; done
    printf '.\n'
  done
}

# _repo: an empty consumer checkout; pages are written into it, then _commit stages them.
_repo() { local d; d="$(mktemp -d "${_work}/repo.XXXXXX")"; git -C "${d}" init -q; printf '%s' "${d}"; }
_commit() { t_git_commit "$1"; }
# _graded <repo>: an empty census, so every page meets the fixed limits; then commit.
_graded() { : > "$1/doc-prose.census"; _commit "$1"; }
_gate() { "${PY}" "${GATE}" --root "$@"; }
# _value <repo> <page> <column>: one figure of --report (2 avg, 3 long share, 4 ids per k, 5 bold per k).
_value() { _gate "$1" --report 2>/dev/null | awk -v p="$2" -v c="$3" '$1 == p { print $c }'; }

_section_split() {
  local d
  t_case "a list item ends its sentence, even without a full stop"
  d="$(_repo)"
  for _ in $(seq 12); do printf -- '- Alpha word word word word word word word word\n'; done > "${d}/list.md"
  _commit "${d}"
  t_assert_eq "9.0" "$(_value "${d}" list.md 2)" "twelve nine-word items are twelve sentences"

  t_case "code fences, tables, inline code and link targets are not prose"
  d="$(_repo)"
  { _sentences 5 20
    printf '\n```\n'; _sentences 10 40 code; printf '```\n\n'
    printf '| Alpha %s |\n|---|\n' "$(_sentences 1 60 cell)"
    printf 'Alpha see `2026-11-24` and [the guide](https://example.invalid/2026-11-24/D11) and more words here.\n'
  } > "${d}/page.md"
  _commit "${d}"
  t_assert_eq "18.3" "$(_value "${d}" page.md 2)" "only the five sentences and the closing one count"
  t_assert_eq "0.0" "$(_value "${d}" page.md 4)" "a date in inline code or a link target is no date in the prose"

  t_case "dates, decision ids and bold count per 1000 words, a short page as 1000"
  d="$(_repo)"
  { _sentences 10 20; printf 'Alpha 2026-11-24 brought CON295 and D11 with **two** and **bold** words.\n'; } > "${d}/ids.md"
  _commit "${d}"
  t_assert_eq "3.0" "$(_value "${d}" ids.md 4)" "a date and two ids in a 212-word page"
  t_assert_eq "2.0" "$(_value "${d}" ids.md 5)" "two bold spans"

  t_case "a generated reST page is not one long sentence, and an admonition is prose"
  d="$(_repo)"
  { printf 'Graphs\n======\n\n.. admonition:: Click\n\n   .. raw:: html\n\n'
    for _ in $(seq 200); do printf '      <div class="graphviz-heading">Class one detection graph</div>\n'; done
  } > "${d}/graphs.rst"
  { printf 'The note page title\n===================\n\n.. note::\n\n'; _sentences 5 20 | sed 's/^/   /'
    printf '\nExample::\n\n'; _sentences 5 50 code | sed 's/^/   /'
    printf '\n=====  =====\nAlpha  Beta\n=====  =====\n%s  x\n=====  =====\n' "$(_sentences 1 40 cell)"
  } > "${d}/note.rst"
  _commit "${d}"
  t_assert_eq "" "$(_value "${d}" graphs.rst 2)" "raw HTML under a directive is no prose, so the page is under 100 words"
  t_assert_eq "20.0" "$(_value "${d}" note.rst 2)" "the note body counts; the title, the literal block and the table do not"
}

_section_records() {
  local d page
  t_case "records, licence texts, vendored and generated pages are not graded"
  d="$(_repo)"
  for page in CHANGELOG.md BACKLOG.md guide/notes-archive-2026.md guide/decisions.md LICENSE.md third_party/lib/README.md; do
    mkdir -p "$(dirname "${d}/${page}")" && _sentences 5 40 > "${d}/${page}"
  done
  { printf '<!-- generated by a tool; do not edit -->\n'; _sentences 5 40; } > "${d}/guide/table.md"
  { _sentences 10 10; printf '<!-- generated:list:start -->\n'; _sentences 5 40; printf '<!-- generated:list:end -->\n'; } > "${d}/guide/mixed.md"
  _graded "${d}"
  t_assert_eq "10.0" "$(_value "${d}" guide/mixed.md 2)" "a generated block inside a page is skipped"
  t_assert_rc 0 _gate "${d}"
}

_section_ratchet() {
  local d
  t_case "a seeded census passes, and a grown value fails"
  d="$(_repo)"
  mkdir -p "${d}/guide"
  _sentences 10 25 > "${d}/guide/page.md"
  _commit "${d}"
  t_assert_rc 0 _gate "${d}" --seed
  t_assert_grep "${d}/doc-prose.census" '^guide/page.md \| avg-sentence \| 25\.0$'
  _sentences 1 45 >> "${d}/guide/page.md"
  t_assert_rc 1 _gate "${d}"
  t_assert_contains "$(_gate "${d}" 2>&1)" "avg-sentence grew from 25 to 26.8"

  t_case "--write never raises a row: a growth stays red"
  t_assert_rc 1 _gate "${d}" --write
  t_assert_grep "${d}/doc-prose.census" '^guide/page.md \| avg-sentence \| 25\.0$'

  t_case "a value that falls fails until --write lowers its row"
  _sentences 10 20 > "${d}/guide/page.md"
  t_assert_rc 1 _gate "${d}"
  t_assert_contains "$(_gate "${d}" 2>&1)" "avg-sentence fell from 25 to 20; lower its row in this commit"
  t_assert_rc 0 _gate "${d}" --write
  t_assert_grep "${d}/doc-prose.census" '^guide/page.md \| avg-sentence \| 20\.0$'

  t_case "rows of a page that is gone fail until --write deletes them"
  git -C "${d}" rm -qf guide/page.md
  t_assert_rc 1 _gate "${d}"
  t_assert_contains "$(_gate "${d}" 2>&1)" "guide/page.md: census rows nothing measures"
  t_assert_rc 0 _gate "${d}" --write
  t_assert_no_grep "${d}/doc-prose.census" 'guide/page.md'

  t_case "a malformed census and a second --seed are refused, not read"
  printf 'guide/page.md | avg-sentence\n' > "${d}/doc-prose.census"
  t_assert_rc 2 _gate "${d}"
  t_assert_rc 2 _gate "${d}" --seed
}

# _limit_pages <repo> <avg words> <31-word sentences> <dates>: one page at or over each fixed limit.
_limit_pages() {
  local i dates=""
  _sentences 5 "$2" > "$1/avg-edge.md"
  { _sentences "$3" 31; _sentences 1 30; _sentences $((19 - $3)) 10; } > "$1/long-edge.md"
  for ((i = 1; i <= $4; i++)); do dates+=" 2026-11-2${i}"; done
  { _sentences 10 20; printf 'Alpha%s word.\n' "${dates}"; } > "$1/ids-edge.md"
}

_section_limits() {
  local d
  t_case "a page without rows meets the fixed limits, at the edge and one over"
  d="$(_repo)"
  _limit_pages "${d}" 22 3 2
  _graded "${d}"
  t_assert_rc 0 _gate "${d}"
  t_assert_eq "15.0" "$(_value "${d}" long-edge.md 3)" "a 30-word sentence is not over 30"
  _limit_pages "${d}" 23 3 2
  t_assert_contains "$(_gate "${d}" 2>&1)" "avg-edge.md: avg-sentence is 23, over the 22"
  _limit_pages "${d}" 22 4 2
  t_assert_contains "$(_gate "${d}" 2>&1)" "long-edge.md: long-share is 20, over the 15"
  _limit_pages "${d}" 22 3 3
  t_assert_rc 1 _gate "${d}"
  t_assert_contains "$(_gate "${d}" 2>&1)" "ids-edge.md: ids-per-k is 3, over the 2"
}

_section_agents() {
  local d
  t_case "a consumer AGENTS.md without a row may hold 3000 words, not 3001"
  d="$(_repo)"
  _sentences 300 10 > "${d}/AGENTS.md"
  _graded "${d}"
  t_assert_rc 0 _gate "${d}"
  t_assert_contains "$(_gate "${d}")" "AGENTS.md: 3000 words, target 3000, within it"
  printf 'Extra.\n' >> "${d}/AGENTS.md"
  t_assert_rc 1 _gate "${d}"
  t_assert_contains "$(_gate "${d}" 2>&1)" "AGENTS.md: words is 3001, over the 3000"

  t_case "a seeded AGENTS.md word count may only fall, and the distance is printed"
  rm "${d}/doc-prose.census"
  t_assert_rc 0 _gate "${d}" --seed
  t_assert_contains "$(_gate "${d}")" "3001 words, target 3000, 1 to go"
  printf 'More.\n' >> "${d}/AGENTS.md"
  t_assert_contains "$(_gate "${d}" 2>&1)" "AGENTS.md: words grew from 3001 to 3002"
}

_section_consumer() {
  local d
  t_case "a consumer without a census is reported, not failed, until it seeds one"
  d="$(_repo)"
  _sentences 5 40 > "${d}/README.md"
  _commit "${d}"
  t_assert_rc 0 _gate "${d}"
  t_assert_contains "$(_gate "${d}")" "OFF for ${d} until doc-prose.census exists"
  t_assert_rc 0 _gate "${d}" --seed
  t_assert_grep "${d}/doc-prose.census" '^README.md \| avg-sentence \| 40\.0$'
}

_section_hub() {
  local hub
  t_case "the hub's own census is required, and its AGENTS.md target is 6000 words"
  hub="$(t_gate_tree verify_doc_prose.py gate_scope.py verify_comment_size.py quality_allow.py)"
  git -C "${hub}" init -q
  _sentences 600 10 > "${hub}/AGENTS.md"
  _commit "${hub}"
  t_assert_rc 2 "${PY}" "${hub}/linux/scripts/verify_doc_prose.py"
  mkdir -p "${hub}/docs/scripts"
  : > "${hub}/docs/scripts/doc-prose.census"
  t_assert_rc 0 "${PY}" "${hub}/linux/scripts/verify_doc_prose.py"
  printf 'Extra.\n' >> "${hub}/AGENTS.md"
  t_assert_contains "$("${PY}" "${hub}/linux/scripts/verify_doc_prose.py" 2>&1)" "AGENTS.md: words is 6001, over the 6000"
  rm -rf "${hub}"
}

_section_wiring() {
  local d
  t_case "run-lint-gates.sh runs the gate over the consumer root"
  # shellcheck source=../run-lint-gates.sh
  source "${SCRIPTS}/run-lint-gates.sh"
  d="$(_repo)"
  _sentences 5 23 > "${d}/README.md"
  _graded "${d}"
  _lint_gates_parse_args "${d}"
  t_assert_eq 1 "$(t_rc _lint_gates_doc_prose)" "a seeded consumer over a limit fails the aggregator"
  rm "${d}/doc-prose.census"
  t_assert_eq 0 "$(t_rc _lint_gates_doc_prose)" "an unseeded one is reported only"
  t_assert_contains "$(cat "${SCRIPTS}/run-lint-gates.sh")" 'run_gate "doc prose" _lint_gates_doc_prose'
}

t_sections _section_split _section_records _section_ratchet _section_limits _section_agents _section_consumer \
  _section_hub _section_wiring -- "$@"
t_summary
