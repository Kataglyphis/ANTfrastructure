#!/usr/bin/env bash
# ==============================================================================
# 30-build-native-nvidia.sh
# Build ONNX Runtime with CUDA, TensorRT, and cuDNN execution providers.
#
# Requires:
#   - CUDA toolkit in /usr/local/cuda (nvcc on PATH)
#   - TensorRT headers/libs in /usr/local/tensorrt or discoverable via
#     pkg-config / TENSORRT_HOME env var
#   - cuDNN headers/libs discoverable via CUDA_CUDNN_* or /usr/local/cuda
#
# Outputs:
#   - Shared libs + headers → ${NATIVE_GPU_OUTPUT_DIR}
#   - Wheel files            → ${NATIVE_GPU_OUTPUT_DIR}/wheels
#   - pkg-config .pc file    → generated by 31-generate-pkgconfig-native.sh
#
# Build Acceleration:
#   USE_CCACHE=true     Enable ccache for faster rebuilds (default: true)
#   USE_LLD=true        Use lld linker for faster linking (default: true)
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/lib/common.sh"

# Source build acceleration helpers if available
for helper in \
    "/opt/scripts/core/compiler-cache.sh" \
    "${SCRIPT_DIR}/../../../../01-core/compiler-cache.sh"; do
    if [ -f "${helper}" ]; then
        # shellcheck disable=SC1090
        source "${helper}"
        setup_ccache
        setup_lld_linker
        break
    fi
done

# --------------------------------------------------------------------------
# Additional defaults specific to the NVIDIA/GPU build
# --------------------------------------------------------------------------
init_nvidia_defaults() {
  # Where to install GPU-accelerated ORT
  NATIVE_GPU_OUTPUT_DIR="${NATIVE_GPU_OUTPUT_DIR:-/usr/local/lib/onnxruntime-gpu}"

  # CUDA paths (CUDA 13.x installs to /usr/local/cuda)
  CUDA_HOME="${CUDA_HOME:-/usr/local/cuda}"

  # TensorRT: prefer TENSORRT_HOME, fall back to standard paths
  TENSORRT_HOME="${TENSORRT_HOME:-/usr/local/tensorrt}"
  if [ ! -d "${TENSORRT_HOME}" ] || [ ! -f "${TENSORRT_HOME}/include/NvInfer.h" ]; then
    TRT_INC=$(find /usr/include /usr/local -name "NvInfer.h" -print -quit 2>/dev/null || true)
    if [ -n "$TRT_INC" ]; then
      # Make a local symlink so TENSORRT_HOME has /include and /lib
      mkdir -p /tmp/tensorrt/include /tmp/tensorrt/lib
      ln -snf "$(dirname "$TRT_INC")"/* /tmp/tensorrt/include/
      ARCH="$(uname -m)"
      case "$ARCH" in
        x86_64) DEB_ARCH="x86_64-linux-gnu" ;;
        aarch64) DEB_ARCH="aarch64-linux-gnu" ;;
        *) DEB_ARCH="$ARCH" ;;
      esac
      if [ -d "/usr/lib/${DEB_ARCH}" ]; then
        ln -snf /usr/lib/${DEB_ARCH}/libnvinfer* /tmp/tensorrt/lib/ 2>/dev/null || true
      fi
      ln -snf /usr/lib/libnvinfer* /tmp/tensorrt/lib/ 2>/dev/null || true
      TENSORRT_HOME="/tmp/tensorrt"
    else
      for candidate in /usr /usr/local; do
        if [ -f "${candidate}/include/NvInfer.h" ]; then
          TENSORRT_HOME="${candidate}"
          break
        fi
      done
    fi
  fi

  # cuDNN: usually ships as part of CUDA or in /usr/lib/x86_64-linux-gnu
  CUDNN_HOME="${CUDNN_HOME:-${CUDA_HOME}}"

  # Build directory for GPU variant (separate from CPU build)
  NATIVE_GPU_BUILD_DIR="${NATIVE_GPU_BUILD_DIR:-${ORT_SRC_DIR}/build_native_gpu}"
}

parse_nvidia_args() {
  parse_common_args "$@"
  init_nvidia_defaults
}

parse_nvidia_args "$@"
detect_jobs

# --------------------------------------------------------------------------
# Sanity-check: CUDA must be present
# --------------------------------------------------------------------------
if [ ! -x "${CUDA_HOME}/bin/nvcc" ]; then
  err "nvcc not found at ${CUDA_HOME}/bin/nvcc. Ensure CUDA is installed and CUDA_HOME is correct."
fi
CUDA_VERSION_FULL="$("${CUDA_HOME}/bin/nvcc" --version | grep "release" | awk '{print $5}' | tr -d ',')"
info "CUDA version: ${CUDA_VERSION_FULL}"

# TensorRT check
if [ ! -f "${TENSORRT_HOME}/include/NvInfer.h" ]; then
  err "TensorRT headers not found at ${TENSORRT_HOME}/include/NvInfer.h. \
Set TENSORRT_HOME to your TensorRT installation."
fi
info "TensorRT home: ${TENSORRT_HOME}"

# cuDNN check
CUDNN_H=""
for candidate in \
    "${CUDNN_HOME}/include/cudnn.h" \
    "${CUDNN_HOME}/include/cudnn_version.h" \
    /usr/include/cudnn.h \
    /usr/local/include/cudnn.h \
    /usr/include/x86_64-linux-gnu/cudnn.h \
    /usr/include/x86_64-linux-gnu/cudnn_version.h \
    /usr/include/aarch64-linux-gnu/cudnn.h \
    /usr/include/aarch64-linux-gnu/cudnn_version.h; do
  if [ -f "${candidate}" ]; then
    CUDNN_H="${candidate}"
    if [[ "${candidate}" == "/usr/include/"* ]]; then
      CUDNN_HOME="/usr"
    elif [[ "${candidate}" == "/usr/local/include/"* ]]; then
      CUDNN_HOME="/usr/local"
    fi
    break
  fi
done
if [ -z "${CUDNN_H}" ]; then
  err "cuDNN headers not found. Ensure cuDNN is installed and CUDNN_HOME is correct."
fi
info "cuDNN header: ${CUDNN_H}"

# --------------------------------------------------------------------------
# Install Python build dependencies
# --------------------------------------------------------------------------
sudo apt-get update -qq && sudo apt-get install -y --no-install-recommends libgcc-s1

info "Using existing Python virtual environment (expected at /opt/python/.venv)"
uv pip install numpy wheel setuptools
HOST_PYTHON="$(host_python_bin)"
export PYTHON_EXECUTABLE="${HOST_PYTHON}" \
       Python_EXECUTABLE="${HOST_PYTHON}" \
       Python3_EXECUTABLE="${HOST_PYTHON}"

# --------------------------------------------------------------------------
# Validate build script
# --------------------------------------------------------------------------
BUILD_SH="${ORT_SRC_DIR}/build.sh"
[[ -x "${BUILD_SH}" ]] || err "build.sh not found at ${BUILD_SH}"

info ">>> Native GPU build (CUDA+TensorRT+cuDNN): ${NATIVE_CPU_CONFIG} (${JOBS} parallel jobs)"
info "Using Python: ${HOST_PYTHON}"
info "NumPy version: $(${HOST_PYTHON} -c 'import numpy; print(numpy.__version__)')"

# --------------------------------------------------------------------------
# Prepare output directories
# --------------------------------------------------------------------------
mkdir -p "${NATIVE_GPU_OUTPUT_DIR}"/{lib,include,wheels}

# --------------------------------------------------------------------------
# Build ONNX Runtime with GPU EPs
# --------------------------------------------------------------------------
# Key flags:
#   --use_cuda            – enable the CUDA Execution Provider
#   --use_tensorrt        – enable the TensorRT Execution Provider
#   --use_full_protobuf   – required by TensorRT EP
#   --cuda_home           – path to CUDA toolkit
#   --cudnn_home          – path to cuDNN headers/libs
#   --tensorrt_home       – path to TensorRT headers/libs

BUILD_ARGS=(
  --build_dir          "${NATIVE_GPU_BUILD_DIR}"
  --config             "${NATIVE_CPU_CONFIG}"
  --build_shared_lib
  --parallel           "${JOBS}"
  --build_wheel
  --compile_no_warning_as_error
  --skip_submodule_sync
  --skip_tests
  --allow_running_as_root
  --use_cuda
  --use_tensorrt
  --use_full_protobuf
  --cuda_home          "${CUDA_HOME}"
  --cudnn_home         "${CUDNN_HOME}"
  --tensorrt_home      "${TENSORRT_HOME}"
  --cmake_extra_defines "CMAKE_CUDA_ARCHITECTURES=80;86;89;90a"
  --use_xnnpack
  --enable_lto
  --use_mimalloc
  --use_lock_free_queue
  --use_webgpu
  --use_external_dawn
)

# Add lld linker for faster linking
if command -v ld.lld >/dev/null 2>&1 && [ "${USE_LLD:-true}" != "false" ]; then
  BUILD_ARGS+=(
    --cmake_extra_defines
    CMAKE_EXE_LINKER_FLAGS=-fuse-ld=lld
    CMAKE_SHARED_LINKER_FLAGS=-fuse-ld=lld
    CMAKE_MODULE_LINKER_FLAGS=-fuse-ld=lld
  )
  info "Using lld linker for faster linking"
fi

# Add ccache for faster compilation
if command -v ccache >/dev/null 2>&1 && [ "${USE_CCACHE:-true}" != "false" ]; then
  BUILD_ARGS+=(
    --cmake_extra_defines
    CMAKE_C_COMPILER_LAUNCHER=ccache
    CMAKE_CXX_COMPILER_LAUNCHER=ccache
  )
  info "Using ccache for faster compilation"
fi

"${BUILD_SH}" "${BUILD_ARGS[@]}"

# --------------------------------------------------------------------------
# Collect artifacts
# --------------------------------------------------------------------------
info "Searching for wheel files..."
find "${NATIVE_GPU_BUILD_DIR}" -name "*.whl" -type f 2>/dev/null | while read -r whl; do
  info "Copying wheel: ${whl}"
  cp "${whl}" "${NATIVE_GPU_OUTPUT_DIR}/wheels/"
  ls -lh "${NATIVE_GPU_OUTPUT_DIR}/wheels/$(basename "${whl}")"
done || info "No wheels found in ${NATIVE_GPU_BUILD_DIR}"

# Copy headers
cp -a "${ORT_SRC_DIR}/include" "${NATIVE_GPU_OUTPUT_DIR}/" 2>/dev/null || \
  warn "Include directory not found at ${ORT_SRC_DIR}/include"

# Flatten headers for GenAI - it expects headers at include/ root
for search_dir in "${ORT_SRC_DIR}" "${NATIVE_GPU_BUILD_DIR}"; do
  if [[ ! -d "${search_dir}/include" ]]; then
    continue
  fi
  find "${search_dir}/include" -name "onnxruntime*.h" -type f 2>/dev/null | while read -r hdr; do
    cp "${hdr}" "${NATIVE_GPU_OUTPUT_DIR}/include/" 2>/dev/null || true
  done
done

# Copy libraries
mkdir -p "${NATIVE_GPU_OUTPUT_DIR}/lib"
find "${NATIVE_GPU_BUILD_DIR}/${NATIVE_CPU_CONFIG}" -maxdepth 1 -type f \
  \( -name "libonnxruntime*.so*" -o -name "libonnxruntime_providers_*.so*" \) \
  -exec cp -t "${NATIVE_GPU_OUTPUT_DIR}/lib/" {} + 2>/dev/null || true

# Create unversioned symlink for libonnxruntime.so (required by GenAI CMake)
onnx_lib="$(find "${NATIVE_GPU_OUTPUT_DIR}/lib" -maxdepth 1 -name 'libonnxruntime.so.*' -type f | head -1)"
if [[ -n "${onnx_lib}" ]] && [[ ! -e "${NATIVE_GPU_OUTPUT_DIR}/lib/libonnxruntime.so" ]]; then
  ln -sf "$(basename "${onnx_lib}")" "${NATIVE_GPU_OUTPUT_DIR}/lib/libonnxruntime.so"
  info "Created symlink: libonnxruntime.so -> $(basename "${onnx_lib}")"
fi

# Symlink into /usr/local/lib for discovery
find "${NATIVE_GPU_OUTPUT_DIR}/lib" -type f -name "lib*.so*" -print0 2>/dev/null | \
  xargs -0 -r ln -sf -t /usr/local/lib/ 2>/dev/null || true

ldconfig 2>/dev/null || true

info "GPU build complete. Artifacts in ${NATIVE_GPU_OUTPUT_DIR}"
info "Wheels in ${NATIVE_GPU_OUTPUT_DIR}/wheels"
ls -lh "${NATIVE_GPU_OUTPUT_DIR}/wheels"/*.whl 2>/dev/null || true
ls -lh "${NATIVE_GPU_OUTPUT_DIR}/lib"/*.so* 2>/dev/null | head -20 || true
