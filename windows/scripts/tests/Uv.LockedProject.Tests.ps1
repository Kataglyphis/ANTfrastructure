#requires -Version 7.0
# Tests locked uv export, installation, cleanup and failures; it does not contact package indexes.

Import-Module (Join-Path (Get-RepoRoot) 'windows\scripts\modules\WindowsUv.Common.psm1') -Force -DisableNameChecking

function New-LockedFixture {
    param([string]$Root)
    $project = Join-Path $Root 'project with spaces'
    $null = New-Item -ItemType Directory -Force -Path $project
    Set-Content -LiteralPath (Join-Path $project 'pyproject.toml') -Value '[project]'
    Set-Content -LiteralPath (Join-Path $project 'uv.lock') -Value 'version = 1'
    return $project
}

function New-LockedRunner {
    param([System.Collections.IDictionary]$State)
    return {
        param($exe, $argv)
        $State.Calls.Add([pscustomobject]@{ Exe = $exe; Args = @($argv) })
        if ($exe -eq 'uv' -and $argv[0] -eq 'export') {
            $State.Export = $argv[-1]
            if ($State.Mode -eq 'export-fails') { throw 'export failed' }
            if ($State.Mode -eq 'header') { Set-Content -LiteralPath $State.Export -Value '# generated by uv' }
            elseif ($State.Mode -eq 'whitespace') { Set-Content -LiteralPath $State.Export -Value '  ' }
            elseif ($State.Mode -eq 'ort') { Set-Content -LiteralPath $State.Export -Value 'onnxruntime_gpu==1 --hash=sha256:abc' }
            elseif ($State.Mode -eq 'ort-extra') { Set-Content -LiteralPath $State.Export -Value 'onnxruntime[extra]==1 --hash=sha256:abc' }
            elseif ($State.Mode -ne 'empty') { Set-Content -LiteralPath $State.Export -Value 'demo==1 --hash=sha256:abc' }
        }
        if ($exe -eq 'uv' -and $argv[0] -eq 'pip' -and $State.Mode -eq 'install-fails') { throw 'install failed' }
        if ($State.Mode -eq 'output') { 'child output' }
    }.GetNewClosure()
}

function Invoke-LockedFixture {
    param([scriptblock]$Body, [string]$Mode = 'ok')
    Invoke-InTestDir { param($dir)
        $project = New-LockedFixture $dir
        $state = @{ Calls = [Collections.Generic.List[object]]::new(); Export = ''; Mode = $Mode }
        & $Body $project $state (New-LockedRunner $state)
    }
}

Describe 'Install-UvLockedProject' {
    It 'exports with the selected interpreter, installs hashes without dependency resolution and applies the lexer fix' {
        Invoke-LockedFixture { param($project, $state, $runner)
            Invoke-WithEnv @{ UV_PYTHON = 'incorrect-python' } {
                Install-UvLockedProject -VenvPython 'C:\venv with spaces\Scripts\python.exe' -ProjectPath $project -CommandRunner $runner
            }
            Assert-Equal 3 $state.Calls.Count 'export, install and patch'
            Assert-Equal 'export' $state.Calls[0].Args[0] 'export runs first'
            Assert-True ($state.Calls[0].Args -contains '--locked') 'lock is mandatory'
            Assert-Equal $project $state.Calls[0].Args[2] 'project path stays one argument'
            Assert-Equal 'C:\venv with spaces\Scripts\python.exe' $state.Calls[0].Args[4] 'the target interpreter overrides UV_PYTHON'
            Assert-True ($state.Calls[1].Args -contains '--no-deps') 'other packages remain untouched'
            Assert-True ($state.Calls[1].Args -contains '--require-hashes') 'only locked hashes install'
            Assert-Equal $state.Export $state.Calls[1].Args[-1] 'install consumes the exported lock'
            Assert-Match 'cmakelang-py315\.py$' $state.Calls[2].Args[-1] 'the existing patch runs last'
            Assert-False (Test-Path -LiteralPath $state.Export) 'the temporary export is removed'
        }
    }

    It 'rejects missing files, bad exports, forbidden ONNX Runtime and install failures' {
        $cases = @(
            @{ Remove = 'pyproject.toml'; Mode = 'ok'; Message = 'pyproject.toml'; Calls = 0; Store = '' },
            @{ Remove = 'uv.lock'; Mode = 'ok'; Message = 'uv.lock'; Calls = 0; Store = '' },
            @{ Remove = ''; Mode = 'export-fails'; Message = 'export failed'; Calls = 1; Store = '' },
            @{ Remove = ''; Mode = 'empty'; Message = 'empty lock export'; Calls = 1; Store = '' },
            @{ Remove = ''; Mode = 'header'; Message = 'empty lock export'; Calls = 1; Store = '' },
            @{ Remove = ''; Mode = 'whitespace'; Message = 'empty lock export'; Calls = 1; Store = '' },
            @{ Remove = ''; Mode = 'install-fails'; Message = 'install failed'; Calls = 2; Store = '' },
            @{ Remove = ''; Mode = 'ort'; Message = 'ONNX Runtime'; Calls = 1; Store = 'C:\chain wheels' },
            @{ Remove = ''; Mode = 'ort-extra'; Message = 'ONNX Runtime'; Calls = 1; Store = 'C:\chain wheels' }
        )
        foreach ($case in $cases) {
            Invoke-LockedFixture -Mode $case.Mode -Body { param($project, $state, $runner)
                if ($case.Remove) { Remove-Item -LiteralPath (Join-Path $project $case.Remove) }
                Invoke-WithEnv @{ ORT_CHAIN_WHEEL_DIR = $case.Store } {
                    Assert-Throws { Install-UvLockedProject -VenvPython 'python.exe' -ProjectPath $project -CommandRunner $runner } -MessagePattern $case.Message
                }
                Assert-Equal $case.Calls $state.Calls.Count 'no further commands may run after failure'
                if ($state.Export) { Assert-False (Test-Path -LiteralPath $state.Export) 'the export is removed on failure' }
            }
        }
    }

    It 'does not return child output as an extra path' {
        Invoke-LockedFixture -Mode 'output' -Body { param($project, $state, $runner)
            $result = @(Install-UvLockedProject -VenvPython 'python.exe' -ProjectPath $project -CommandRunner $runner)
            Assert-Equal 0 $result.Count 'child output cannot leak to callers'
        }
    }

    It 'resolves relative projects and overrides a poisoned uv working directory in both commands' {
        Invoke-LockedFixture { param($project, $state, $runner)
            Push-Location (Split-Path $project -Parent)
            try {
                Invoke-WithEnv @{ UV_WORKING_DIR = (Get-RepoRoot); UV_PROJECT = (Get-RepoRoot) } {
                    Install-UvLockedProject -VenvPython 'relative/python' -ProjectPath './project with spaces' -CommandRunner $runner
                    Assert-Equal (Get-RepoRoot) $env:UV_WORKING_DIR 'the inherited setting remains unchanged'
                }
                Assert-Equal $project $state.Calls[0].Args[2] 'project resolves against the caller directory'
                foreach ($call in $state.Calls[0..1]) {
                    $index = [Array]::IndexOf($call.Args, '--directory')
                    Assert-True ($index -ge 0) 'both uv commands override UV_WORKING_DIR'
                    Assert-Equal (Get-Location).ProviderPath $call.Args[$index + 1] 'relative paths use the caller directory'
                    $projectIndex = [Array]::IndexOf($call.Args, '--project')
                    Assert-True ($projectIndex -ge 0) 'both uv commands override UV_PROJECT'
                    Assert-Equal $project $call.Args[$projectIndex + 1] 'both uv commands use the selected project'
                }
            } finally { Pop-Location }
        }
    }

    It 'keeps the copied module, locked project and Python compatibility patch as one usable closure' {
        Invoke-InTestDir { param($dir)
            $root = Get-RepoRoot
            $modules = Join-Path $dir 'windows/scripts/modules'
            Copy-TestModuleClosure -Seed WindowsUv.Common -Destination $modules
            $project = Join-Path $dir 'quality/cmake-format'
            $compat = Join-Path $dir 'linux/scripts/lib/cmakelang-py315.py'
            $null = [IO.Directory]::CreateDirectory($project)
            $null = [IO.Directory]::CreateDirectory((Split-Path $compat -Parent))
            foreach ($name in @('pyproject.toml', 'uv.lock')) {
                Copy-Item -LiteralPath (Join-Path $root "quality/cmake-format/$name") -Destination $project -ErrorAction Stop
            }
            Copy-Item -LiteralPath (Join-Path $root 'linux/scripts/lib/cmakelang-py315.py') -Destination $compat -ErrorAction Stop
            $moduleLiteral = ConvertTo-TestPwshLiteral -Value (Join-Path $modules 'WindowsUv.Common.psm1')
            $projectLiteral = ConvertTo-TestPwshLiteral -Value $project
            $source = @"
`$ErrorActionPreference = 'Stop'
Import-Module $moduleLiteral -Force -DisableNameChecking
`$runner = { param(`$exe, `$argv) if (`$exe -eq 'uv' -and `$argv[0] -eq 'export') { Set-Content -LiteralPath `$argv[-1] -Value 'demo==1' } }
Install-UvLockedProject -VenvPython 'python.exe' -ProjectPath $projectLiteral -CommandRunner `$runner
"@
            $control = Invoke-TestPwshProbe -Source $source
            Assert-Equal 0 $control.ExitCode $control.Output
            Remove-Item -LiteralPath (Join-Path $project 'uv.lock')
            Assert-TestPwshFailure -Probe (Invoke-TestPwshProbe -Source $source) -Pattern 'uv.lock' -Reason 'missing lock must fail'
            Copy-Item -LiteralPath (Join-Path $root 'quality/cmake-format/uv.lock') -Destination $project -ErrorAction Stop
            Remove-Item -LiteralPath $compat
            Assert-TestPwshFailure -Probe (Invoke-TestPwshProbe -Source $source) -Pattern '(?s)cmakelang-py315.py.*missing' -Reason 'missing patch must fail'
        }
    }
}
